"use strict";
// Concatenates src/*.js (name order) into dist/Code.gs, the file the owner pastes into Apps Script.
const fs = require("node:fs");
const path = require("node:path");

const HEADER = "// GENERATED by tools/usage-sheet/build.js from src/*.js. Do not edit; edit src/ and rebuild.";

function buildSource() {
  const srcDir = path.join(__dirname, "src");
  const files = fs.readdirSync(srcDir).filter((f) => f.endsWith(".js")).sort();
  const parts = files.map((f) => fs.readFileSync(path.join(srcDir, f), "utf8"));
  return [HEADER].concat(parts).join("\n");
}

module.exports = { buildSource };

if (require.main === module) {
  const out = path.join(__dirname, "dist", "Code.gs");
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, buildSource());
  console.log("wrote " + out);
}
